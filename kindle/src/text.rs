pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;

fn glyph(c: u8) -> &'static [u8; 5] {
    let c = c.to_ascii_uppercase();
    let idx = c.wrapping_sub(FIRST) as usize;
    GLYPHS.get(idx).unwrap_or(&GLYPHS[0])
}

/// Width in pixels that `draw` will occupy, including inter-character gaps.
pub fn text_width(s: &str, scale: u32) -> u32 {
    if s.is_empty() {
        return 0;
    }
    let n = s.len() as u32;
    n * GLYPH_W * scale + (n - 1) * scale
}

/// Draw `s` with its top-left at (x, y), each font pixel scaled to
/// `scale` x `scale`. Returns the x just past the last glyph.
pub fn draw(fb: &mut Framebuffer, x: u32, y: u32, scale: u32, s: &str, fg: u8) -> u32 {
    let mut cx = x;
    for ch in s.bytes() {
        let g = glyph(ch);
        for (col, bits) in g.iter().enumerate() {
            for row in 0..GLYPH_H {
                if bits & (1 << row) == 0 {
                    continue;
                }
                let px = cx + col as u32 * scale;
                let py = y + row * scale;
                for dy in 0..scale {
                    for dx in 0..scale {
                        fb.set(px + dx, py + dy, fg);
                    }
                }
            }
        }
        cx += (GLYPH_W + 1) * scale;
    }
    cx
}
