#!/usr/bin/env python3
"""Ship a frozen, one-time saved-selection conversion to offline clients.

The v1 asset records historical choices. Never rebuild it from the current
catalog: that would lose the preferences of clients returning after retirement.
This data does not resolve server routes or agent/operation workload pins.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET = ROOT / "ui/unified-ui/src/lib/llm/legacySelections.v1.json"
SWIFT = ROOT / "magios/Magios/LegacyLlmSelections.generated.swift"
KOTLIN = ROOT / "magdroid/android/bridge/src/main/kotlin/ai/magicbeans/magdroid/chat/LegacyLlmSelections.generated.kt"


def load_asset() -> dict:
    value = json.loads(ASSET.read_text())
    if (value.get("schema_version") != 1
            or value.get("purpose") != "one_time_saved_selection_migration"
            or value.get("runtime_alias_resolver") is not False):
        raise ValueError("invalid one-time preference migration asset")
    for kind in ("chat", "coding"):
        for old, selection in value[kind].items():
            expected = {"model_id", "thinking"} | ({"kind", "engine"} if kind == "coding" else set())
            if set(selection) != expected or not old or not all(isinstance(v, str) and v.strip() == v and v for v in selection.values()):
                raise ValueError(f"invalid {kind} preference conversion: {old}")
            if kind == "coding" and selection["kind"] != "model":
                raise ValueError("coding conversion must preserve the selected engine/model")
    if set(value["chat"]) & set(value["unavailable_chat_ids"]):
        raise ValueError("unavailable choices cannot be converted")
    return value


def outputs(asset: dict) -> dict[Path, str]:
    digest = hashlib.sha256(ASSET.read_bytes()).hexdigest()
    entries = json.dumps(asset["chat"], sort_keys=True, separators=(",", ":"))
    # These are raw string literals in both languages. Refuse delimiters and
    # Kotlin interpolation rather than silently emitting different native data.
    if '"""' in entries or '$' in entries or '\\' in entries:
        raise ValueError("unsupported characters in frozen preference migration data")
    header = f"// Generated by scripts/llm_preference_migration_codegen.py; do not edit.\n// Frozen v1 asset SHA-256: {digest}\n"
    swift = header + '''import Foundation

/// Consulted only when a typed saved preference is absent. Never a route resolver.
enum LegacyLlmSelections {
    private static let chat: [String: ChatModelSelection] = {
        let data = Data(#"""
''' + entries + '''
        """#.utf8)
        return (try? JSONDecoder().decode([String: ChatModelSelection].self, from: data)) ?? [:]
    }()

    static func chatSelection(for legacyID: String) -> ChatModelSelection? { chat[legacyID] }
}
'''
    # Swift multiline content must share the closing delimiter's indentation.
    swift = swift.replace("\n" + entries + "\n", "\n        " + entries + "\n")
    kotlin = header + '''package ai.magicbeans.magdroid.chat

import kotlinx.serialization.json.Json

/** Consulted only without a typed saved preference; never a route resolver. */
internal object LegacyLlmSelections {
    private val chat: Map<String, ChatModelSelection> by lazy {
        Json.decodeFromString<Map<String, ChatModelSelection>>("""
''' + entries + '''
        """.trimIndent())
    }

    fun chatSelection(legacyId: String): ChatModelSelection? = chat[legacyId]
}
'''
    return {SWIFT: swift, KOTLIN: kotlin}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = outputs(load_asset())
    stale = []
    for path, content in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise SystemExit("Stale preference migration outputs: " + ", ".join(stale))
    print("One-time LLM preference migration outputs " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
