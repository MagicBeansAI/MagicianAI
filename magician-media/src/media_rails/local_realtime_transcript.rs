    #[test]
    fn bounded_command_queue_reports_overload_and_closure() {
        let (commands, receiver) = mpsc::channel(1);
        let handle = LocalRealtimeTranscriptHandle {
            commands,
            profile_id: Arc::from("test-profile"),
            next_stream_generation: Arc::new(AtomicU64::new(1)),
            suppressed_event_generations: Arc::new(RwLock::new(HashSet::new())),
            queued_audio_bytes: Arc::new(AtomicUsize::new(0)),
            queued_audio_frames: Arc::new(AtomicUsize::new(0)),
            queue_high_water_bytes: Arc::new(AtomicUsize::new(0)),
            dropped_audio_frames: Arc::new(AtomicU64::new(0)),
        };

        handle.try_push_audio(vec![1, 2]).expect("first command");
        assert_eq!(
            handle.try_commit(),
            Err(LocalRealtimeTranscriptCommandError::QueueFull)
        );
        assert_eq!(handle.current_stream_generation(), 1);
        assert_eq!(
            handle.try_clear(),
            Err(LocalRealtimeTranscriptCommandError::QueueFull)
        );
        assert_eq!(handle.current_stream_generation(), 1);
        assert!(handle
            .suppressed_event_generations
            .read()
            .expect("suppressed generations")
            .is_empty());
        assert_eq!(
            handle.try_push_audio(vec![3, 4, 5]),
            Err(LocalRealtimeTranscriptCommandError::QueueFull)
        );
        assert_eq!(
            handle.queue_snapshot(),
            LocalRealtimeTranscriptQueueSnapshot {
                queued_audio_bytes: 2,
                queued_audio_frames: 1,
                high_water_audio_bytes: 2,
                dropped_audio_frames: 1,
            }
        );

        drop(receiver);
        assert_eq!(
            handle.try_end(),
            Err(LocalRealtimeTranscriptCommandError::Closed)
        );
        assert!(handle
            .suppressed_event_generations
            .read()
            .expect("suppressed generations")
            .is_empty());
    }

