/// Older Gemini models keep the studio roster. Gemini 3.8 accepts the full
/// prebuilt library; preserve the documented studio aliases without duplicates.
pub fn gemini_voices(extended: bool) -> &'static [&'static str] {
    if !extended {
        return GEMINI_STUDIO_VOICES;
    }
    static ALL: OnceLock<Vec<&'static str>> = OnceLock::new();
    ALL.get_or_init(|| {
        GEMINI_STUDIO_VOICES
            .iter()
            .chain(GEMINI_EXTENDED_VOICES)
            .copied()
            .collect()
    })
    .as_slice()
}
