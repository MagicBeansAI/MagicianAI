#!/usr/bin/env python3
"""Generate main/star_body.c: the Magican star mascot's body for the face page.

The source is the brand board's "hi" pose (ui/unified-ui/static/brand/
mascot-hi-{light,dark}.svg, frame 15 of hi.json). The eye arcs and the thrown
ball are removed; the body, its shine, the glasses, arms and legs stay. The
firmware draws the eyes and mouth live on top, so they follow the device's
real state (listening, thinking, speaking) instead of being baked in.

Output is LVGL 9 RGB565A8 (RGB565 plane, then an 8-bit alpha plane), drawn
straight from flash: no decode buffer, no RAM copy.

Needs rsvg-convert (Homebrew librsvg) and Pillow. Run from anywhere:
    python3 magesp/tools/star/gen_star_body.py
"""
from __future__ import annotations

import pathlib
import re
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[3]
BRAND = ROOT / "ui/unified-ui/static/brand"
OUT_C = ROOT / "magesp/main/star_body.c"
OUT_H = ROOT / "magesp/main/star_body.h"

# Path order in the pose (both themes share it): 12/13 eye arcs,
# 19 the ball's motion dashes, 20 its highlight, 21 the ball.
DROP = (12, 13, 19, 20, 21)
# Arms, hands, legs and feet (3-6, 15-18) are near-black ink. On the device's
# black dark theme that ink vanishes, so the dark build draws them warm white;
# the glasses sit on the star's yellow and keep the ink.
LIMBS = (3, 4, 5, 6, 15, 16, 17, 18)
INK = "rgb(20,17,14)"
LIMB_ON_DARK = "rgb(242,230,208)"
HEIGHT = 300          # device pixels; the 368x448 panel keeps its bottom for text
RENDER = 1024         # render big, then downscale, for clean edges

# Where the live features go, in the 512 viewBox of the source pose.
LENS_L = (217.5, 284.0)
LENS_R = (294.5, 284.0)
MOUTH = (256.0, 345.0)


def strip(svg: str, dark: bool) -> str:
    paths = list(re.finditer(r"<path\b[^>]*?/>|<path\b[^>]*?>.*?</path>", svg, re.S))
    if len(paths) != 22:
        sys.exit(f"expected the 22-path hi pose, found {len(paths)} paths")
    for i in sorted(set(DROP) | (set(LIMBS) if dark else set()), reverse=True):
        m = paths[i]
        text = "" if i in DROP else m.group(0).replace(INK, LIMB_ON_DARK)
        svg = svg[: m.start()] + text + svg[m.end():]
    return svg


def render(theme: str) -> Image.Image:
    svg = strip((BRAND / f"mascot-hi-{theme}.svg").read_text(), theme == "dark")
    with tempfile.TemporaryDirectory() as tmp:
        src, png = pathlib.Path(tmp, "s.svg"), pathlib.Path(tmp, "s.png")
        src.write_text(svg)
        subprocess.run(["rsvg-convert", "-w", str(RENDER), "-h", str(RENDER), str(src), "-o", str(png)], check=True)
        return Image.open(png).convert("RGBA")


def rgb565a8(img: Image.Image) -> bytes:
    rgb = bytearray()
    alpha = bytearray()
    for r, g, b, a in img.getdata():
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb += bytes((v & 0xFF, v >> 8))      # little-endian RGB565
        alpha.append(a)
    return bytes(rgb + alpha)


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main() -> None:
    light, dark = render("light"), render("dark")
    box = light.getchannel("A").getbbox()
    dark_box = dark.getchannel("A").getbbox()
    box = (min(box[0], dark_box[0]), min(box[1], dark_box[1]), max(box[2], dark_box[2]), max(box[3], dark_box[3]))
    scale = HEIGHT / (box[3] - box[1])
    width = round((box[2] - box[0]) * scale)
    k = RENDER / 512

    def place(pt):
        return (round((pt[0] * k - box[0]) * scale), round((pt[1] * k - box[1]) * scale))

    images = {}
    for theme, img in (("light", light), ("dark", dark)):
        images[theme] = img.crop(box).resize((width, HEIGHT), Image.LANCZOS)

    (lx, ly), (rx, ry), (mx, my) = place(LENS_L), place(LENS_R), place(MOUTH)
    lens_r = round((48.5 - 13) * k * scale)   # inner lens radius: ring 48.5, stroke ~13
    header = f"""/* Generated by tools/star/gen_star_body.py -- do not edit by hand. */
#pragma once
#include "lvgl.h"

#define STAR_W        {width}
#define STAR_H        {HEIGHT}
/* Feature anchors inside the star image, in its own pixels. */
#define STAR_LENS_LX  {lx}
#define STAR_LENS_RX  {rx}
#define STAR_LENS_Y   {ly}
#define STAR_LENS_R   {lens_r}
#define STAR_MOUTH_X  {mx}
#define STAR_MOUTH_Y  {my}

extern const lv_image_dsc_t star_body_light;
extern const lv_image_dsc_t star_body_dark;
"""
    body = ['/* Generated by tools/star/gen_star_body.py -- do not edit by hand. */\n#include "star_body.h"\n']
    for theme, img in images.items():
        data = rgb565a8(img)
        body.append(c_array(f"star_{theme}_map", data))
        body.append(f"""
const lv_image_dsc_t star_body_{theme} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565A8,
        .w = STAR_W,
        .h = STAR_H,
        .stride = STAR_W * 2,
    }},
    .data_size = sizeof star_{theme}_map,
    .data = star_{theme}_map,
}};
""")
    OUT_H.write_text(header)
    OUT_C.write_text("\n".join(body))
    for theme, img in images.items():
        img.save(OUT_C.parent.parent / "tools/star" / f"preview-{theme}.png")
    print(f"star {width}x{HEIGHT}, lenses ({lx},{ly}) ({rx},{ry}) r{lens_r}, mouth ({mx},{my})")


if __name__ == "__main__":
    main()
