//! The uniform record one eval run leaves behind.
//!
//! # Why this record exists at all
//!
//! The 31 eval lanes write 31 mutually incompatible reports. Nothing about them
//! is going to be unified — they belong to the evals, not to the page. This
//! record is the thin uniform layer produced *outside* the lanes: enough to say
//! what ran, when, how long it took, and whether it passed, for every lane,
//! without touching any of them.
//!
//! # Why there is no cost field
//!
//! Money has exactly one source of truth: the LLM ledger. A run links to the
//! execution that produced it via [`EvalRun::task_id`] and cost is joined at
//! read time from the ledger. Copying a dollar figure in here would freeze it —
//! and the ledger reprices (a corrected rate, a late-arriving usage record), so
//! the copy would silently become a second, wrong answer that nothing would ever
//! reconcile. A join that returns "unknown" is a visible gap; a stale number is
//! not.
//!
//! # Why every persisted status is terminal
//!
//! [`EvalRunStatus`] has no `Running`. A record is written once, when the run
//! has ended, so the store is *history* and history is append-only — see
//! [`super::store`]. Whatever is in flight right now is the runner's business to
//! hold in memory; persisting it here would mean mutating records, which is the
//! one thing a trend series must not allow.
//!
//! # Why `Interrupted` is not `Failed`
//!
//! A cancelled or crashed run learned nothing about the eval. Folding it into
//! `Failed` would put a red mark on a lane that was never actually judged, and
//! folding it into `Passed` would be worse. It is a third outcome because it is
//! a third outcome.

use serde::{Deserialize, Serialize};

use super::registry::EvalRequirement;

/// Bumped when a stored record stops being readable by the previous shape.
pub const EVAL_RUN_SCHEMA_VERSION: u16 = 1;

/// Hard ceiling on [`EvalRun::log_tail`], in bytes.
///
/// This is a *diagnostic* excerpt, not a log store: enough to see the assertion
/// that fired and the lines around it, and small enough that reading a lane's
/// whole history stays cheap — [`super::store::EvalRunStore::list`] deserializes
/// every record it returns, so an unbounded field here would be paid on every
/// page load, forever, by a page that only renders the tail of one of them.
pub const MAX_LOG_TAIL_BYTES: usize = 8 * 1024;

/// How a run ended. There is no non-terminal variant — see the module docs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EvalRunStatus {
    /// The lane ran to completion and reported success.
    Passed,
    /// The lane ran to completion and reported failure. This is a *judgement*
    /// about the eval.
    Failed,
    /// Cancelled or crashed. NEVER conflate with `Passed`: nothing was judged,
    /// so a run that ended this way is evidence about the machine, not about
    /// the code under eval.
    Interrupted,
}

impl EvalRunStatus {
    /// Whether the run actually judged the thing it was pointed at.
    ///
    /// Trend lines and pass rates must be computed over judged runs only:
    /// counting an `Interrupted` run as a failure invents a regression, and
    /// counting it as a pass hides one.
    pub const fn is_judgement(self) -> bool {
        matches!(self, Self::Passed | Self::Failed)
    }
}

/// One completed run of one eval lane, in the same shape for all 31 lanes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct EvalRun {
    pub schema_version: u16,
    /// Unique within the lane; it is also the file name. Generated by
    /// [`EvalRun::new_run_id`] so that two runs can never collide and silently
    /// overwrite each other's history.
    pub run_id: String,
    /// The [`super::registry::EvalLane::id`] this run belongs to.
    pub lane_id: String,
    pub principal: String,
    pub workspace: String,
    /// The execution that ran this lane. **Cost joins on this** (Task 6): the
    /// LLM ledger is keyed by task, so a run with no `task_id` is a run whose
    /// spend cannot be attributed — which the page must render as unknown
    /// rather than as zero.
    pub task_id: Option<String>,
    /// Epoch milliseconds, UTC.
    pub started_at_ms: i64,
    pub duration_ms: i64,
    pub status: EvalRunStatus,
    /// The process exit code, when the run produced one. Absent for a run that
    /// never got far enough to have one (and for `Interrupted` runs killed by a
    /// signal), which is why it is not folded into `status`.
    pub exit_code: Option<i32>,
    /// The requirements this lane declared *at the time it ran*, snapshotted so
    /// that later editing the Makefile annotation cannot rewrite what an old run
    /// needed. A trend line is only readable if the past stays fixed.
    pub services: Vec<EvalRequirement>,
    /// Deep link to the lane's own (non-uniform) report for this run.
    pub report_href: Option<String>,
    /// Optional parameters captured when the run started. Absent in older records.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub options: Option<super::options::EvalRunOptions>,
    /// The last [`MAX_LOG_TAIL_BYTES`] bytes of output. Always set through
    /// [`EvalRun::set_log_tail`] or bounded on the way to disk by the store, so
    /// a lane that printed a gigabyte cannot land a gigabyte in the scope.
    pub log_tail: Option<String>,
}

impl EvalRun {
    /// A run that has started and not yet been judged.
    ///
    /// The status starts at [`EvalRunStatus::Interrupted`] deliberately: it is
    /// the truthful description of a run nobody finished, and it is the only
    /// default that is safe to persist by accident. Defaulting to `Passed`
    /// would let a dropped record read as a green lane, which is precisely the
    /// lie this record exists to prevent.
    pub fn new(
        run_id: impl Into<String>,
        lane_id: impl Into<String>,
        principal: impl Into<String>,
        workspace: impl Into<String>,
        started_at_ms: i64,
    ) -> Self {
        Self {
            schema_version: EVAL_RUN_SCHEMA_VERSION,
            run_id: run_id.into(),
            lane_id: lane_id.into(),
            principal: principal.into(),
            workspace: workspace.into(),
            task_id: None,
            started_at_ms,
            duration_ms: 0,
            status: EvalRunStatus::Interrupted,
            exit_code: None,
            services: Vec::new(),
            report_href: None,
            options: None,
            log_tail: None,
        }
    }

    /// A fresh run id: `evr_<zero-padded start millis>_<8 hex>`.
    ///
    /// Time-prefixed and zero-padded so that lexical order matches chronological
    /// order — the store sorts by `started_at_ms` first, but a directory listing
    /// (and the id tie-break between two runs that started in the same
    /// millisecond) then reads chronologically too. The random suffix is what
    /// makes a collision — and therefore a lost run record — impossible in
    /// practice, including across two runners started at the same instant.
    pub fn new_run_id(started_at_ms: i64) -> String {
        let stamp = started_at_ms.max(0);
        let suffix = uuid::Uuid::new_v4().simple().to_string();
        format!("evr_{stamp:013}_{}", &suffix[..8])
    }

    /// Sets [`EvalRun::log_tail`] from arbitrarily long output, keeping only the
    /// final [`MAX_LOG_TAIL_BYTES`] bytes.
    pub fn set_log_tail(&mut self, log: &str) {
        self.log_tail = bound_log_tail(log);
    }

    /// Re-applies the [`MAX_LOG_TAIL_BYTES`] bound to whatever is currently in
    /// [`EvalRun::log_tail`].
    ///
    /// The fields are public, so [`EvalRun::set_log_tail`] can be bypassed. The
    /// store calls this on the way to disk so the bound is a property of the
    /// stored data rather than of the caller's discipline. Bounding an already
    /// bounded tail is a no-op, so calling it twice cannot compound the elision
    /// marker.
    pub fn enforce_log_tail_bound(&mut self) {
        if let Some(log) = self.log_tail.take() {
            self.log_tail = bound_log_tail(&log);
        }
    }
}

/// Bounds `log` to its final [`MAX_LOG_TAIL_BYTES`] bytes, prefixed with a note
/// saying how much was dropped. Empty input yields `None`.
///
/// The *end* is what survives, because that is where a failing eval says why it
/// failed. The note matters as much as the bound: without it, a fragment that
/// happens to start mid-sentence is indistinguishable from a complete log, and
/// whoever is reading it goes looking for a beginning that was never stored.
pub fn bound_log_tail(log: &str) -> Option<String> {
    if log.is_empty() {
        return None;
    }
    if log.len() <= MAX_LOG_TAIL_BYTES {
        return Some(log.to_string());
    }
    // The note is part of the budget, so the stored field is bounded, not
    // "bounded plus a bit". Sizing it against the *whole* log guarantees the
    // width is sufficient: `omitted` can never have more digits than `log.len()`.
    let note_width = elision_note(log.len()).len();
    let budget = MAX_LOG_TAIL_BYTES.saturating_sub(note_width);
    let kept = tail_from_char_boundary(log, budget);
    Some(format!("{}{kept}", elision_note(log.len() - kept.len())))
}

fn elision_note(omitted_bytes: usize) -> String {
    format!("[... {omitted_bytes} earlier bytes omitted]\n")
}

/// The last `max_bytes` (or fewer) bytes of `text`, starting at a character
/// boundary.
///
/// Slicing a `&str` at an arbitrary byte offset panics, and log output is full
/// of multi-byte characters — box-drawing in a progress bar, an emoji in a test
/// name, a snippet of non-ASCII fixture data. The cut snaps *forward* to the
/// next boundary, so the result is always valid UTF-8 and never longer than
/// `max_bytes` (snapping backwards would be valid too, but could exceed the
/// budget by up to three bytes, which would quietly break the bound this
/// function exists to enforce).
fn tail_from_char_boundary(text: &str, max_bytes: usize) -> &str {
    if text.len() <= max_bytes {
        return text;
    }
    let mut start = text.len() - max_bytes;
    while start < text.len() && !text.is_char_boundary(start) {
        start += 1;
    }
    &text[start..]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_new_run_is_interrupted_until_something_judges_it() {
        // The safe default: a record nobody finished must never read as green.
        let run = EvalRun::new("evr_1", "eval-monitor-golden", "anonymous", "default", 10);
        assert_eq!(run.status, EvalRunStatus::Interrupted);
        assert!(!run.status.is_judgement());
        assert_eq!(run.schema_version, EVAL_RUN_SCHEMA_VERSION);
        assert_eq!(run.task_id, None);
        assert_eq!(run.log_tail, None);
    }

    /// Interrupted runs are not evidence about the code under eval, so a pass
    /// rate computed over them is fiction in both directions.
    #[test]
    fn only_passed_and_failed_are_judgements() {
        assert!(EvalRunStatus::Passed.is_judgement());
        assert!(EvalRunStatus::Failed.is_judgement());
        assert!(!EvalRunStatus::Interrupted.is_judgement());
    }

    #[test]
    fn a_run_round_trips_through_json_in_snake_case() {
        let mut run = EvalRun::new("evr_1", "eval-monitor-golden", "anonymous", "default", 1700);
        run.task_id = Some("task_42".into());
        run.status = EvalRunStatus::Passed;
        run.duration_ms = 4200;
        run.exit_code = Some(0);
        run.services = vec![EvalRequirement::Ollama, EvalRequirement::MagicianBinary];
        run.report_href = Some("/evals/reports/monitor".into());

        let json = serde_json::to_value(&run).unwrap();
        assert_eq!(json["schema_version"], 1);
        assert_eq!(json["lane_id"], "eval-monitor-golden");
        assert_eq!(json["task_id"], "task_42");
        assert_eq!(json["started_at_ms"], 1700);
        assert_eq!(json["status"], "passed");
        assert_eq!(json["services"][1], "magician_binary");

        let restored: EvalRun = serde_json::from_value(json).unwrap();
        assert_eq!(restored, run);
    }

    /// Cost is joined from the LLM ledger by `task_id` at read time (Task 6).
    /// A stored dollar figure would freeze a number the ledger can still
    /// correct, giving the same run two answers and no way to reconcile them.
    #[test]
    fn a_run_record_carries_no_cost() {
        let run = EvalRun::new("evr_1", "lane", "anonymous", "default", 0);
        let json = serde_json::to_value(&run).unwrap();
        let object = json.as_object().unwrap();
        for field in object.keys() {
            assert!(
                !field.contains("cost") && !field.contains("usd"),
                "cost must be joined from the ledger, never stored: found `{field}`"
            );
        }
        assert!(
            object.contains_key("task_id"),
            "the join key must be stored"
        );
    }

    #[test]
    fn a_short_log_tail_is_stored_verbatim() {
        let mut run = EvalRun::new("evr_1", "lane", "anonymous", "default", 0);
        run.set_log_tail("assertion failed: 1 == 2\n");
        assert_eq!(run.log_tail.as_deref(), Some("assertion failed: 1 == 2\n"));

        run.set_log_tail("");
        assert_eq!(run.log_tail, None, "an empty log is absent, not empty text");
    }

    /// Multi-byte safety: truncation must not split a UTF-8 char. Slicing a
    /// `&str` at an arbitrary byte offset panics, and eval output is full of
    /// box-drawing, emoji and non-ASCII fixture data.
    #[test]
    fn an_oversized_log_tail_is_truncated_on_a_char_boundary() {
        // 4-byte characters, so the naive cut lands mid-character.
        let log = "\u{1F600}".repeat(MAX_LOG_TAIL_BYTES);
        let mut run = EvalRun::new("evr_1", "lane", "anonymous", "default", 0);
        run.set_log_tail(&log);

        let stored = run.log_tail.as_deref().unwrap();
        assert!(
            stored.len() <= MAX_LOG_TAIL_BYTES,
            "stored {} bytes, bound is {MAX_LOG_TAIL_BYTES}",
            stored.len()
        );
        // Nothing to assert about validity beyond this: a split character would
        // have panicked in `set_log_tail` before reaching here. What this does
        // prove is that no *replacement* character was substituted for one.
        assert!(!stored.contains('\u{FFFD}'));

        // Every offset of a 3-byte character across the cut, so the boundary
        // search is exercised at each of its possible starting positions.
        for pad in 0..8 {
            let log = format!(
                "{}{}",
                "a".repeat(pad),
                "\u{4E2D}".repeat(MAX_LOG_TAIL_BYTES)
            );
            let mut run = EvalRun::new("evr_1", "lane", "anonymous", "default", 0);
            run.set_log_tail(&log);
            let stored = run.log_tail.as_deref().unwrap();
            assert!(stored.len() <= MAX_LOG_TAIL_BYTES, "pad {pad}");
            assert!(stored.ends_with('\u{4E2D}'), "pad {pad}");
        }
    }

    /// It is a *tail*: the end of the log is where a failing eval says why it
    /// failed, so the end is what has to survive.
    #[test]
    fn truncation_keeps_the_end_of_the_log_and_says_what_it_dropped() {
        let log = format!(
            "START\n{}\npanicked at 'assertion failed'\n",
            "x".repeat(MAX_LOG_TAIL_BYTES * 2)
        );
        let stored = bound_log_tail(&log).unwrap();
        assert!(stored.ends_with("panicked at 'assertion failed'\n"));
        assert!(!stored.contains("START"));
        assert!(
            stored.starts_with("[... "),
            "a fragment must not read as a whole log: {}",
            &stored[..40.min(stored.len())]
        );
    }

    #[test]
    fn bounding_an_already_bounded_tail_is_a_no_op() {
        let once = bound_log_tail(&"y".repeat(MAX_LOG_TAIL_BYTES * 3)).unwrap();
        let twice = bound_log_tail(&once).unwrap();
        assert_eq!(twice, once);
    }

    /// The fields are public, so the bound cannot rely on callers using
    /// `set_log_tail` — the store re-applies it on the way to disk.
    #[test]
    fn the_bound_can_be_re_applied_to_a_hand_built_record() {
        let mut run = EvalRun::new("evr_1", "lane", "anonymous", "default", 0);
        run.log_tail = Some("z".repeat(MAX_LOG_TAIL_BYTES * 2));
        run.enforce_log_tail_bound();
        assert!(run.log_tail.as_deref().unwrap().len() <= MAX_LOG_TAIL_BYTES);
    }

    #[test]
    fn a_log_exactly_at_the_bound_is_untouched() {
        let log = "z".repeat(MAX_LOG_TAIL_BYTES);
        let stored = bound_log_tail(&log).unwrap();
        assert_eq!(stored, log);

        let over = "z".repeat(MAX_LOG_TAIL_BYTES + 1);
        let stored = bound_log_tail(&over).unwrap();
        assert!(stored.len() <= MAX_LOG_TAIL_BYTES);
        assert_ne!(stored, over);
    }

    /// Two runs must never collide on an id: the id is the file name, and the
    /// store keys history on it.
    #[test]
    fn run_ids_are_unique_and_sort_chronologically() {
        let early = EvalRun::new_run_id(1_700_000_000_000);
        let late = EvalRun::new_run_id(1_700_000_001_000);
        assert!(early < late, "{early} should sort before {late}");
        assert_ne!(
            EvalRun::new_run_id(1_700_000_000_000),
            EvalRun::new_run_id(1_700_000_000_000),
            "same-millisecond runs must still get distinct ids"
        );
        // Zero padding is what makes the lexical order hold across widths.
        assert!(EvalRun::new_run_id(1) < EvalRun::new_run_id(10));
    }

    /// The id becomes a file name, so it must not need escaping.
    #[test]
    fn a_generated_run_id_is_path_safe() {
        let id = EvalRun::new_run_id(1_700_000_000_000);
        assert!(
            id.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-'),
            "{id}"
        );
    }
}
